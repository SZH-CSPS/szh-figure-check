export const LANGUES = Object.keys(TEXTES);

export function langueInitiale(parametre, navigateur) {
  if (LANGUES.includes(parametre)) return parametre;
  return /^de\b/i.test(navigateur || '') ? 'de' : 'fr';
}

export function T(langue, cle, valeurs = {}) {
  const brut = TEXTES[langue][cle] ?? TEXTES.fr[cle] ?? cle;
  if (typeof brut !== 'string') return brut;
  return brut.replace(/\{(\w+)\}/g, (_m, k) => (k in valeurs ? valeurs[k] : `{${k}}`));
}

export function nombre(valeur, decimales = 1) {
  return valeur.toFixed(decimales).replace('.', ',');
}

